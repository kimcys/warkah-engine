/** The wall-clock parts of an ISO instant in a time zone ("2026-12-12T11:00:00+08:00", "Asia/Kuala_Lumpur"). weekday: 0 = Sunday. */
function partsIn(iso, timeZone) {
	const fmt = new Intl.DateTimeFormat("en-GB", {
		timeZone,
		year: "numeric",
		month: "2-digit",
		day: "2-digit",
		hour: "2-digit",
		minute: "2-digit",
		hourCycle: "h23",
		weekday: "short"
	});
	const p = Object.fromEntries(fmt.formatToParts(new Date(iso)).map((x) => [x.type, x.value]));
	const weekday = [
		"Sun",
		"Mon",
		"Tue",
		"Wed",
		"Thu",
		"Fri",
		"Sat"
	].indexOf(String(p.weekday));
	return {
		y: Number(p.year),
		m: Number(p.month),
		d: Number(p.day),
		h: Number(p.hour),
		min: Number(p.minute),
		weekday
	};
}
function time12(h, min) {
	const suffix = h >= 12 ? "PM" : "AM";
	return `${h % 12 === 0 ? 12 : h % 12}:${String(min).padStart(2, "0")} ${suffix}`;
}
