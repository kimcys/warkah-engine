function validateEvent(data) {
	const result = eventSchema.safeParse(data);
	if (result.success) return { ok: true };
	return {
		ok: false,
		problems: result.error.issues.map((issue) => {
			const path = issue.path.join(".");
			const field = labelFor(path) ?? path;
			let message = issue.message;
			switch (issue.code) {
				case "invalid_type":
					message = String(issue.message).includes("received undefined") ? `Sila isi ${field}.` : `${field} tidak betul.`;
					break;
				case "too_small":
					message = issue.origin === "array" ? `Sila tambah sekurang-kurangnya ${issue.minimum} untuk ${field}.` : issue.origin === "string" ? `${field} terlalu pendek.` : `${field} terlalu kecil (minimum ${issue.minimum}).`;
					break;
				case "too_big":
					message = issue.origin === "array" ? `${field} terlalu banyak (maksimum ${issue.maximum}).` : `${field} terlalu besar (maksimum ${issue.maximum}).`;
					break;
				case "invalid_format":
					message = issue.format === "url" ? `${field} mesti pautan penuh bermula dengan https://` : issue.format === "datetime" ? `${field} mesti tarikh dan masa yang sah.` : `Format ${field} tidak betul.`;
					break;
				case "invalid_value": message = `Pilihan ${field} tidak sah. Pilih salah satu: ${issue.values.join(", ")}.`;
			}
			return {
				path,
				field,
				message
			};
		})
	};
}
